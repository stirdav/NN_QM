include("system.jl")
include("resonant_drive.jl")
using CairoMakie

# ---------------------------------------------------------------------------
# Parameters
# ---------------------------------------------------------------------------
#
# The calculation is dimensionless: g=1 sets the frequency scale and 1/g sets
# the time scale. The physical values below come from Table S2 of the
# supplementary material for Science 380, adf7553 (2023):
#
#   g0/2π             = 258 kHz
#   qubit γ1/2π       =  19 kHz
#   qubit γ2,Ramsey/2π =  24 kHz   (total coherence decay)
#   phonon κ1/2π       = 2.5 kHz
#   phonon κ2,Ramsey/2π = 1.5 kHz   (total adjacent-coherence decay)
#
# The table's γ2 and κ2 are TOTAL decoherence rates, whereas `Dephasing` in
# QuantumDynamics expects a PURE-dephasing coefficient. We therefore remove
# the coherence decay already generated by energy relaxation:
#
#   qubit:  γφ/2π = γ2,Ramsey/2π - (γ1/2π)/2
#                    = 24 - 19/2 = 14.5 kHz
#
# For the oscillator, `Dephasing(:osc, κφ)` constructs sqrt(κφ/2)*n.
# An adjacent Fock coherence then decays at κφ/4, while energy loss adds
# κ1/2. Matching the measured Ramsey rate therefore requires
#
#   κφ/2π = 4[κ2,Ramsey/2π - (κ1/2π)/2]
#          = 4(1.5 - 2.5/2) = 1.0 kHz.
#
# The echo values in the table are 21 kHz (qubit) and 1.4 kHz (phonon), but
# Ramsey values are used here because this preparation has no echo refocusing.
# The physical numbers remain comments only; the solver receives their ratios
# to g0 below.
N = 3
g = 1.0
γ1 = 19.0 / 258.0  # qubit energy relaxation: (19 kHz)/(258 kHz)
γ2 = 14.5 / 258.0  # qubit pure dephasing: (14.5 kHz)/(258 kHz)
κ1 = 2.5 / 258.0   # phonon energy relaxation: (2.5 kHz)/(258 kHz)
κ2 = 1.0 / 258.0   # phonon number dephasing: (1.0 kHz)/(258 kHz)

# The always-on JC coupling can disturb the intended qubit flip. Choosing
# g*w=0.01 keeps the pulse short compared with the vacuum-Rabi time and gives
# the worst-case leakage parameter g*sqrt(N)*w ≈ 0.017 for N=3.
w = 0.01
τ = 0.1w  # smooth tanh-edge width; also used as the solver's dtmax

# `run_open_fock_prep` constructs ρ(0)=|g,0⟩⟨g,0|, builds all four
# collapse operators, and dispatches to the time-dependent master-equation
# solver. Its returned `states` are density operators rather than kets.
r = run_open_fock_prep(
    N, fock_ladder_hamiltonian_resonant;
    g, w, τ, γ1, γ2, κ1, κ2,
)

# ---------------------------------------------------------------------------
# Observables
# ---------------------------------------------------------------------------
qb, ob = getsubsystem(r.cs, :qubit).basis, getsubsystem(r.cs, :osc).basis

# P_n = |g,n⟩⟨g,n| + |e,n⟩⟨e,n| traces over the qubit and therefore
# measures only the probability that the oscillator contains n excitations.
projectors = [
    projector(spindown(qb) ⊗ fockstate(ob, k)) +
    projector(spinup(qb) ⊗ fockstate(ob, k))
    for k in 0:N
]
pop = [real(expect(P, ρ)) for ρ in r.states, P in projectors]

# The preparation target is specifically |g,N⟩, so this is stricter than the
# oscillator-only n=N population above: residual qubit excitation counts as an
# error even when the oscillator has reached the desired Fock level.
target = spindown(qb) ⊗ fockstate(ob, N)
target_population = [real(expect(projector(target), ρ)) for ρ in r.states]

# The embedded Pauli-z expectation tracks the qubit inversion. With the
# QuantumOptics spin convention used by this package, |e⟩=|up⟩ has ⟨σz⟩=+1
# and |g⟩=|down⟩ has ⟨σz⟩=-1. Each drive pulse raises the trace toward +1;
# the following JC swap returns it toward -1 while adding one oscillator quantum.
σz = op(r.cs, :qubit, :σz)
σz_expectation = [real(expect(σz, ρ)) for ρ in r.states]

# Since g=1, the horizontal coordinate is the dimensionless time gt and the
# drive is shown relative to g. This makes the result independent of which
# physical coupling frequency is used to interpret the comments above.
gt = g .* r.tout
Ω_over_g = r.Ωfun.(r.tout) ./ g

fig = Figure(size=(700, 800))
ax1 = Axis(fig[1, 1], ylabel="population",
    title="Dissipative resonant preparation: |g,0⟩ → |g,$N⟩")
for k in 0:N
    lines!(ax1, gt, pop[:, k+1], label="n=$k")
end
for s in r.steps
    vspan!(ax1, g*s.c, g*s.d, color=(:gray, 0.15))
end
axislegend(ax1, position=:rc)

ax2 = Axis(fig[2, 1], ylabel="P(g,N)")
lines!(ax2, gt, target_population, color=:dodgerblue)
for s in r.steps
    vspan!(ax2, g*s.c, g*s.d, color=(:gray, 0.15))
end

ax3 = Axis(fig[3, 1], ylabel="⟨σz⟩")
lines!(ax3, gt, σz_expectation, color=:crimson)
for s in r.steps
    vspan!(ax3, g*s.c, g*s.d, color=(:gray, 0.15))
end

ax4 = Axis(fig[4, 1], xlabel="dimensionless time gt", ylabel="Ω(t)/g")
lines!(ax4, gt, Ω_over_g, color=:black)
for s in r.steps
    vspan!(ax4, g*s.c, g*s.d, color=(:gray, 0.15))
end

# All four axes share time, and the gray regions identify the intervals in
# which the drive is off and the resonant JC interaction performs each swap.
linkxaxes!(ax1, ax2, ax3, ax4)
hidexdecorations!(ax1, grid=false)
hidexdecorations!(ax2, grid=false)
hidexdecorations!(ax3, grid=false)
rowsize!(fig.layout, 4, Relative(0.18))

save("population_ladder.png", fig)
println("Dimensionless parameters: g=$g, γ1=$γ1, γ2=$γ2, κ1=$κ1, κ2=$κ2, w=$w")
println("Final |g,$N⟩ population: ", target_population[end])
println("Saved population_ladder.png")
